/**
 * Deterministic coordinate resolver for any AirKorea station when getMsrstnList is unavailable.
 */
export function resolveKoreaStationCoord(
  sidoName: string,
  stationName: string,
  dynamicMap?: Map<string, [number, number]>
): [number, number] | null {
  if (dynamicMap) {
    const exact = dynamicMap.get(`${sidoName}:${stationName}`) ?? dynamicMap.get(stationName);
    if (exact) return exact;
  }

  // Exact match on stationName
  if (KOREA_DISTRICT_COORDS[stationName]) {
    return KOREA_DISTRICT_COORDS[stationName];
  }

  // Prefix / substring match (e.g., "수원시 영통구" or "강남대로" -> "강남구" / "수원")
  for (const [key, coords] of Object.entries(KOREA_DISTRICT_COORDS)) {
    if (stationName.includes(key) || (key.length >= 2 && stationName.startsWith(key.slice(0, 2)))) {
      return coords;
    }
  }

  // Fall back to Sido center with slight deterministic jitter so multiple stations don't stack identically
  const base = KOREA_SIDO_CENTERS[sidoName];
  if (!base) return null;
  let hash = 0;
  for (let i = 0; i < stationName.length; i++) {
    hash = (hash * 31 + stationName.charCodeAt(i)) | 0;
  }
  const jLat = (((hash & 0xff) / 255) - 0.5) * 0.28;
  const jLng = ((((hash >> 8) & 0xff) / 255) - 0.5) * 0.28;
  return [
    Math.round((base[0] + jLat) * 1000) / 1000,
    Math.round((base[1] + jLng) * 1000) / 1000,
  ];
}
